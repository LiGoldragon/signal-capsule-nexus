#[rustfmt::skip]
#[allow(clippy::large_enum_variant)]
pub enum Answer {
    Once(Output),
    Subscribed(signal::Stream<Panes, Known>),
}
#[rustfmt::skip]
#[allow(clippy::result_large_err, clippy::ptr_arg, clippy::borrowed_box)]
pub trait Answering {
    fn create(&self, workspace: &Workspace) -> core::result::Result<Outcome, Output>;
    fn start(&self, start: &Start_Data) -> core::result::Result<Outcome, Output>;
    fn prompt(&self, prompt: &Prompt_Data) -> core::result::Result<Outcome, Output>;
    fn press(&self, press: &Press_Data) -> core::result::Result<Outcome, Output>;
    fn close(&self, pane: &Pane) -> core::result::Result<Outcome, Output>;
    fn list(&self, session: &Session) -> core::result::Result<Outcome, Output>;
    fn subscribe(
        &self,
        session: &Session,
    ) -> core::result::Result<signal::Stream<Panes, Known>, Output>;
}
#[rustfmt::skip]
pub trait Answerable {
    type Answer;
    fn answer<Nexus: Answering>(&self, nexus: &Nexus) -> Self::Answer;
}
#[rustfmt::skip]
impl Answerable for Input {
    type Answer = Answer;
    fn answer<Nexus: Answering>(&self, nexus: &Nexus) -> Answer {
        match self {
            Input::Create(carried) => {
                Answer::Once(
                    nexus.create(carried).map_or_else(|refusal| refusal, Output::Created),
                )
            }
            Input::Start(carried) => {
                Answer::Once(
                    nexus.start(carried).map_or_else(|refusal| refusal, Output::Started),
                )
            }
            Input::Prompt(carried) => {
                Answer::Once(
                    nexus
                        .prompt(carried)
                        .map_or_else(|refusal| refusal, Output::Prompted),
                )
            }
            Input::Press(carried) => {
                Answer::Once(
                    nexus.press(carried).map_or_else(|refusal| refusal, Output::Pressed),
                )
            }
            Input::Close(carried) => {
                Answer::Once(
                    nexus.close(carried).map_or_else(|refusal| refusal, Output::Closed),
                )
            }
            Input::List(carried) => {
                Answer::Once(
                    nexus.list(carried).map_or_else(|refusal| refusal, Output::Listed),
                )
            }
            Input::Subscribe(carried) => {
                nexus.subscribe(carried).map_or_else(Answer::Once, Answer::Subscribed)
            }
        }
    }
}
